int main(void)
{
    uint32_t n = 1;
    uint8_t  i, fails;

    bsp_init();
    uart1_init();
    i2c_init();

    printf("\r\n\r\n");
    printf("============================================\r\n");
    printf("  501 毕设 —— OLED 中文显示测试\r\n");
    printf("============================================\r\n");
    printf("  字库里有 %u 个汉字: %s\r\n", cnfont_count, cnfont_chars);
    printf("============================================\r\n\r\n");

    printf("【探测】");
    if (i2c_probe(OLED_ADDR) == I2C_OK) printf(" 找到 OLED\r\n");
    else                                 printf(" X 找不到 OLED\r\n");

    printf("【初始化】... ");
    fails = oled_init_seq();
    printf("%s\r\n\r\n", fails ? "★ 有失败" : "√");

    delay_ms(300);

    while (1) {
        printf("\r\n████ 第 %u 轮 ████\r\n", (unsigned)n);

        /* ===== ① 英文标题 ===== */
        printf("  【①】英文标题... ");
        clear();
        putstr(0, 0, "  STM32 Health Helper");
        putstr(0, 2, "  Chinese Display Test");
        putstr(0, 4, "  Font: SimHei 16x16");
        putstr(0, 6, "  Chars loaded: ");
        putnum(90, 6, (int32_t)cnfont_count);
        fails = oled_refresh();
        printf("%s\r\n", fails ? "★ 失败" : "√");
        delay_ms(2000);

        /* ===== ② 中文两行（★ 主角） ===== */
        printf("  【②】中文显示... ");
        clear();
        /* 「欣欣你在干什么」 7 个字 × 16 = 112 列，居中偏左 */
        draw_cn(8, 0, "欣欣你在干什么");
        /* 「我好想你」 4 个字 × 16 = 64 列，居中 */
        draw_cn(32, 3, "我好想你");
        putstr(20, 7, ">_<  ~");
        fails = oled_refresh();
        printf("%s\r\n", fails ? "★ 失败" : "√");
        delay_ms(4000);

        /* ===== ③ 中文 + 动态数字 ===== */
        printf("  【③】中文 + 计数器... ");
        clear();
        draw_cn(0, 0, "欣欣你在干什么");
        putstr(0, 3, "Count:");
        putstr(0, 5, "I2C err:");
        fails = oled_refresh();
        printf("%s\r\n", fails ? "★ 失败" : "√");

        for (i = 1; i <= 8; i++) {
            /* 只清数字区域 */
            memset(&gram[3][48], 0, 24);
            memset(&gram[5][60], 0, 24);
            putnum(48, 3, (int32_t)i);
            putnum(60, 5, (int32_t)g_err);
            oled_refresh();
            printf("      计数 = %u\r\n", i);
            delay_ms(600);
        }

        /* ===== ④ 中文滚动 ===== */
        printf("  【④】中文横向滚动... ");
        {
            int16_t off;
            /* 把「我好想你」放在一个宽的虚拟画布上滚动 */
            for (off = 0; off < 5; off++) {
                clear();
                draw_cn((uint8_t)(off * 24), 2, "我好想你");
                oled_refresh();
                delay_ms(180);
            }
            for (off = 4; off >= 0; off--) {
                clear();
                draw_cn((uint8_t)(off * 24), 2, "我好想你");
                oled_refresh();
                delay_ms(180);
            }
        }
        printf("√\r\n");

        /* ===== ⑤ 统计 ===== */
        printf("  【⑤】统计... ");
        clear();
        draw_cn(16, 0, "我好想你");
        putstr(0, 3, "Refresh OK");
        putstr(0, 5, "I2C errors:");
        putnum(78, 5, (int32_t)g_err);
        putstr(0, 7, g_err == 0 ? "STATUS: PERFECT" : "STATUS: HAS ERR");
        fails = oled_refresh();
        printf("%s\r\n", fails ? "★ 失败" : "√");
        delay_ms(3000);

        n++;
        if (n > 999) n = 1;
    }
}
