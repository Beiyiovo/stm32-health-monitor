/**
 ******************************************************************************
 *  19_oled_cn —— ★ OLED 中文显示测试
 ******************************************************************************
 *  目的：
 *      让 OLED 显示中文（16×16 点阵）
 *
 *  ★ 字库来源：_common/cnfont.c（由 Python 脚本从 Windows 字体生成）
 *      当前字库包含这些字：欣 你 在 干 什 么 我 好 想
 *      ★ 想显示别的字，改 generate_cnfont.py 里的 TEXT 再跑一次
 *
 *  ★ 显示效果（循环）：
 *      ① 英文标题
 *      ② 中文两行：「欣欣你在干什么」「我好想你」
 *      ③ 中文 + 滚动
 *      ④ 回到 ①
 *
 *  接线：
 *      OLED GND → STM32【G】
 *      OLED VCC → STM32【3.3】
 *      OLED SCL → STM32【B6】
 *      OLED SDA → STM32【B7】
 *      ★ 两个 4.7kΩ：B6←→3.3、B7←→3.3
 *      USB-TTL：TXD→A10、RXD→A9、GND→G
 ******************************************************************************
 */
#include "bsp.h"
#include "i2c.h"
#include "cnfont.h"

#define OLED_ADDR   0x3C
#define W           128
#define PAGES       8

static uint8_t gram[PAGES][W];
static uint32_t g_err = 0;

/* ==================== 底层 ==================== */

static uint8_t oled_cmd(uint8_t c)
{
    return i2c_write_regs(OLED_ADDR, 0x00, &c, 1);
}

static uint8_t oled_data(const uint8_t *d, uint16_t len)
{
    return i2c_write_regs(OLED_ADDR, 0x40, d, len);
}

static uint8_t oled_refresh(void)
{
    uint8_t page, fails = 0;
    for (page = 0; page < PAGES; page++) {
        if (oled_cmd((uint8_t)(0xB0 + page)) != I2C_OK) { fails++; continue; }
        if (oled_cmd(0x00) != I2C_OK) { fails++; continue; }
        if (oled_cmd(0x10) != I2C_OK) { fails++; continue; }
        if (oled_data(gram[page], W) != I2C_OK) { fails++; }
    }
    g_err += fails;
    return fails;
}

static uint8_t oled_init_seq(void)
{
    uint8_t fail = 0;
    static const uint8_t seq[] = {
        0xAE, 0x20, 0x10, 0xB0, 0xC8, 0x00, 0x10, 0x40,
        0x81, 0xFF, 0xA1, 0xA6, 0xA8, 0x3F, 0xA4, 0xD3,
        0x00, 0xD5, 0xF0, 0xD9, 0x22, 0xDA, 0x12, 0xDB,
        0x20, 0x8D, 0x14, 0xAF
    };
    uint8_t i;
    for (i = 0; i < sizeof(seq); i++) {
        if (oled_cmd(seq[i]) != I2C_OK) fail++;
        delay_ms(2);
    }
    return fail;
}

