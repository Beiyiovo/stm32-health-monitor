/**
 ******************************************************************************
 *  18_oled_display —— ★ OLED 综合显示测试（带 I2C 错误检测）
 ******************************************************************************
 *  目的：
 *      ① 让 OLED 显示各种内容（文字、数字、进度条、图案）
 *      ② ★ 检测 I2C 写入是否稳定（每次写都检查 ACK，失败就报错）
 *      ③ 诊断"亮一下就黑"的原因
 *
 *  它会循环做：
 *      阶段 1  全屏点亮（全白）      —— 证明屏幕能全亮
 *      阶段 2  全屏熄灭（全黑）
 *      阶段 3  显示 8 行文字
 *      阶段 4  计数器（数字每秒变）  —— 验证刷新正常
 *      阶段 5  进度条（左右增长）
 *      阶段 6  显示图案（边框 + 方块）
 *      阶段 7  回到阶段 1
 *
 *  ★ 每个阶段都会检查 I2C 是否写成功：
 *      成功 → 串口打印 OK
 *      失败 → 打印 ★ I2C 错误！并累计错误次数
 *
 *  ★ 接线：
 *      OLED GND → STM32【G】
 *      OLED VCC → STM32【3.3】
 *      OLED SCL → STM32【B6】
 *      OLED SDA → STM32【B7】
 *      ★ 两个 4.7kΩ：B6←→3.3、B7←→3.3
 *      USB-TTL：TXD→A10、RXD→A9、GND→G
 ******************************************************************************
 */
#include "bsp.h"
#include "i2c.h"

#define OLED_ADDR   0x3C
#define W           128
#define PAGES       8

/* 显存 */
static uint8_t gram[PAGES][W];

/* 统计 */
static uint32_t g_ok = 0;
static uint32_t g_err = 0;

/* ==================== 带错误检测的底层 ==================== */

/* 写命令，返回 0 = 成功 */
static uint8_t oled_cmd(uint8_t c)
{
    return i2c_write_regs(OLED_ADDR, 0x00, &c, 1);
}

/* 写数据，返回 0 = 成功 */
static uint8_t oled_data(const uint8_t *d, uint16_t len)
{
    return i2c_write_regs(OLED_ADDR, 0x40, d, len);
}

/* ★ 逐页刷新，检查每一页是否成功；返回失败页数 */
static uint8_t oled_refresh_checked(void)
{
    uint8_t page, fails = 0;

    for (page = 0; page < PAGES; page++) {
        if (oled_cmd((uint8_t)(0xB0 + page)) != I2C_OK) { fails++; continue; }
        if (oled_cmd(0x00) != I2C_OK) { fails++; continue; }
        if (oled_cmd(0x10) != I2C_OK) { fails++; continue; }
        if (oled_data(gram[page], W) != I2C_OK) { fails++; }
    }

    if (fails == 0) g_ok++;
    else            g_err += fails;

    return fails;
}

