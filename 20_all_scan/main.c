/**
 ******************************************************************************
 *  20_all_scan —— ★★★ 三模块一起扫描 + OLED 中文显示
 ******************************************************************************
 *  功能：
 *      ① 扫描 I2C 总线，列出所有在线设备
 *      ② 在 OLED 上显示扫描结果（英文）
 *      ③ 在 OLED 上显示中文「冻冻我想你了」
 *      ④ 循环
 *
 *  ★★ 中文显示的 bug 已修：
 *      之前 draw_cn() 里 s++ 每次只前进 1 字节，但 UTF-8 汉字占 3 字节，
 *      导致把一个汉字拆成 3 个字节分别查字库 → 只显示前一两个字。
 *      现在改成：一次跳 3 字节，并按 3 字节比较。
 *
 *  ★★★ 接线（三个模块【并联】在同一组 I2C 总线上）：
 *
 *      OLED 模块：
 *          GND → STM32 下排【G】
 *          VCC → STM32 上排【3.3】
 *          SCL → STM32 下排【B6】
 *          SDA → STM32 下排【B7】
 *
 *      MPU6050 模块（8 脚）：
 *          VCC → STM32【3.3】
 *          GND → STM32【G】
 *          SCL → STM32【B6】
 *          SDA → STM32【B7】
 *          ★ AD0 → STM32【G】      ← 必须！否则地址变 0x69
 *          XDA / XCL / INT → 空着不接
 *
 *      MAX30102 模块（★ 用下排 4 个脚，上排全不接）：
 *          VIN → STM32【3.3】
 *          SDA → STM32【B7】       ← ★ 注意 SDA 在 SCL 前面
 *          SCL → STM32【B6】
 *          GND → STM32【G】
 *
 *      ★ 两个 4.7kΩ 上拉（必须）：
 *          电阻#1：STM32 的【B6】针 ←→【3.3】针
 *          电阻#2：STM32 的【B7】针 ←→【3.3】针
 *
 *      USB-TTL（烧录 + 看打印）：
 *          TXD → STM32【A10】
 *          RXD → STM32【A9】
 *          GND → STM32【G】
 ******************************************************************************
 */
#include "bsp.h"
#include "i2c.h"
#include "cnfont.h"

#define OLED_ADDR   0x3C
#define W           128
#define PAGES       8

static uint8_t gram[PAGES][W];
static uint32_t g_err = 0;

/* ==================== OLED 底层 ==================== */

static uint8_t oled_cmd(uint8_t c)
{
    return i2c_write_regs(OLED_ADDR, 0x00, &c, 1);
}

static uint8_t oled_data(const uint8_t *d, uint16_t len)
{
    return i2c_write_regs(OLED_ADDR, 0x40, d, len);
}

static uint8_t oled_refresh(void)
{
    uint8_t page, fails = 0;
    for (page = 0; page < PAGES; page++) {
        if (oled_cmd((uint8_t)(0xB0 + page)) != I2C_OK) { fails++; continue; }
        if (oled_cmd(0x00) != I2C_OK) { fails++; continue; }
        if (oled_cmd(0x10) != I2C_OK) { fails++; continue; }
        if (oled_data(gram[page], W) != I2C_OK) { fails++; }
    }
    g_err += fails;
    return fails;
}

static uint8_t oled_init_seq(void)
{
    uint8_t fail = 0;
    static const uint8_t seq[] = {
        0xAE, 0x20, 0x10, 0xB0, 0xC8, 0x00, 0x10, 0x40,
        0x81, 0xFF, 0xA1, 0xA6, 0xA8, 0x3F, 0xA4, 0xD3,
        0x00, 0xD5, 0xF0, 0xD9, 0x22, 0xDA, 0x12, 0xDB,
        0x20, 0x8D, 0x14, 0xAF
    };
    uint8_t i;
    for (i = 0; i < sizeof(seq); i++) {
        if (oled_cmd(seq[i]) != I2C_OK) fail++;
        delay_ms(2);
    }
    return fail;
}

