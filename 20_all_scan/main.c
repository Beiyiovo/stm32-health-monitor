static void clear(void) { memset(gram, 0, sizeof(gram)); }

static void putstr(uint8_t x, uint8_t page, const char *s)
{
    if (page >= PAGES) return;
    while (*s) {
        uint8_t ch = (uint8_t)(*s++);
        uint8_t i;
        if (ch < 0x20 || ch > 0x7E) ch = 0x20;
        if (x + 6 > W) break;
        for (i = 0; i < 6; i++) gram[page][x + i] = F6x8[ch - 0x20][i];
        x += 6;
    }
}

static void putnum(uint8_t x, uint8_t page, int32_t v)
{
    char b[16];
    sprintf(b, "%d", (int)v);
    putstr(x, page, b);
}

/* ==================== ★ 中文（已修 UTF-8 bug） ==================== */

/**
 * 在字库里找一个 UTF-8 汉字（★ 按 3 字节比较）
 * 返回索引，0xFF = 没找到
 */
static uint8_t find_cn_utf8(const char *s)
{
    uint8_t i;
    for (i = 0; i < cnfont_count; i++) {
        if ((uint8_t)cnfont_chars[i * 3]     == (uint8_t)s[0] &&
            (uint8_t)cnfont_chars[i * 3 + 1] == (uint8_t)s[1] &&
            (uint8_t)cnfont_chars[i * 3 + 2] == (uint8_t)s[2]) {
            return i;
        }
    }
    return 0xFF;
}

/**
 * ★ 修正版：显示中文（16×16，每个字占 16 列 × 2 页）
 * ★ 关键修复：s += 3（UTF-8 汉字占 3 字节），而不是 s++
 */
static void draw_cn(uint8_t x, uint8_t page, const char *s)
{
    uint8_t i;

    if (page > 6) return;

    while (s[0] && s[1] && s[2]) {              /* 还剩至少 3 字节 */
        uint8_t idx = find_cn_utf8(s);

        if (x + 16 > W) break;

        if (idx != 0xFF) {
            for (i = 0; i < 16; i++) {
                gram[page][x + i]         = cnfont_data[idx][i];        /* 上半 */
                gram[page + 1][x + i]     = cnfont_data[idx][16 + i];   /* 下半 */
            }
        }
        x += 16;
        s += 3;                                  /* ★★★ 关键修复 */
    }
}

/* ==================== 扫描 ==================== */

static const char *dev_name(uint8_t a)
{
    switch (a) {
        case 0x3C: case 0x3D: return "OLED";
        case 0x57:            return "MAX30102";
        case 0x68: case 0x69: return "MPU6050";
        case 0x76:            return "BMP280";
        case 0x1E:            return "HMC5883";
        default:              return "Unknown";
    }
}

/* ==================== 主程序 ==================== */

int main(void)
{
    uint8_t  found[16];
    uint8_t  n;
    uint8_t  addr;
    uint32_t round = 1;
    uint8_t  fails, i;
    int      has_oled, has_max, has_mpu;

    bsp_init();
    uart1_init();
    i2c_init();

    printf("\r\n\r\n");
    printf("============================================\r\n");
    printf("  501 毕设 —— 三模块扫描 + OLED 中文显示\r\n");
    printf("============================================\r\n");
    printf("  接线：三个模块并联在 B6(SCL)/B7(SDA) 上\r\n");
    printf("        ★ 两个 4.7kΩ 上拉：B6<->3.3、B7<->3.3\r\n");
    printf("        ★ MPU6050 的 AD0 必须接 GND\r\n");
    printf("        ★ MAX30102 脚序 VIN·SDA·SCL·GND\r\n");
    printf("============================================\r\n\r\n");

    printf("【OLED 初始化】... ");
    fails = oled_init_seq();
    printf("%s\r\n\r\n", fails ? "★ 有失败" : "√");

    /* 启动画面 */
    clear();
    putstr(16, 2, "STM32 Health");
    putstr(16, 4, "Helper  v1.0");
    oled_refresh();
    delay_ms(1200);

    while (1) {
        printf("\r\n██████████ 第 %u 轮扫描 ██████████\r\n", (unsigned)round);

        /* ===== 扫描 ===== */
        n = 0;
        for (addr = 0x01; addr < 0x80; addr++) {
            if (i2c_probe(addr) == I2C_OK) {
                printf("  发现设备: 0x%02X  (%s)\r\n", addr, dev_name(addr));
                if (n < sizeof(found)) found[n++] = addr;
            }
        }
        printf("  共发现 %u 个设备\r\n", n);

        has_oled = (i2c_probe(0x3C) == I2C_OK || i2c_probe(0x3D) == I2C_OK);
        has_max  = (i2c_probe(0x57) == I2C_OK);
        has_mpu  = (i2c_probe(0x68) == I2C_OK || i2c_probe(0x69) == I2C_OK);

        printf("  [%s] OLED      (0x3C)\r\n", has_oled ? "√" : "X");
        printf("  [%s] MAX30102  (0x57)\r\n", has_max  ? "√" : "X");
        printf("  [%s] MPU6050   (0x68)\r\n", has_mpu  ? "√" : "X");
        printf("\r\n");

        /* ===== OLED 显示扫描结果 ===== */
        clear();
        putstr(0, 0, "=== I2C SCAN ===");
        putstr(0, 1, "Found:");
        putnum(48, 1, (int32_t)n);

        /* 列出每个设备的地址和名字 */
        for (i = 0; i < n && i < 4; i++) {
            putstr(0, (uint8_t)(2 + i), "0x");
            {
                char hx[4];
                sprintf(hx, "%02X", found[i]);
                putstr(12, (uint8_t)(2 + i), hx);
            }
            putstr(30, (uint8_t)(2 + i), dev_name(found[i]));
        }

        /* 状态行 */
        if (has_oled && has_max && has_mpu) {
            putstr(0, 7, "ALL 3 ONLINE  OK");
        } else {
            putstr(0, 7, "MISSING:");
            if (!has_oled) putstr(54, 7, "OLED");
            if (!has_max)  putstr(78, 7, "MAX");
            if (!has_mpu)  putstr(96, 7, "MPU");
        }
        oled_refresh();
        delay_ms(3500);

        /* ===== ★ 中文显示 ===== */
        printf("  OLED 显示中文「冻冻我想你了」... ");
        clear();
        /* 「冻冻」2个字 = 32列，居中放 x=48 */
        draw_cn(48, 0, "冻冻");
        /* 「我想你了」5个字 = 80列，居中放 x=24 */
        draw_cn(24, 3, "我想你了");
        /* 底部加个小装饰 */
        putstr(0, 7, "  *  STM32  *");
        fails = oled_refresh();
        printf("%s\r\n", fails ? "★ 失败" : "√");
        delay_ms(4500);

        /* ===== 中文 + 设备状态 ===== */
        printf("  中文 + 状态显示... ");
        clear();
        draw_cn(32, 0, "冻冻");
        draw_cn(16, 2, "我想你了");
        putstr(0, 5, "OLED:");
        putstr(36, 5, has_oled ? "OK" : "--");
        putstr(0, 6, "MAX :");
        putstr(36, 6, has_max ? "OK" : "--");
        putstr(66, 6, "MPU:");
        putstr(96, 6, has_mpu ? "OK" : "--");
        putstr(0, 7, "Err:");
        putnum(30, 7, (int32_t)g_err);
        fails = oled_refresh();
        printf("%s\r\n", fails ? "★ 失败" : "√");
        delay_ms(4500);

        round++;
        if (round > 999) round = 1;
    }
}
