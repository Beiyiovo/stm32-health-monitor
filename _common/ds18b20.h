#ifndef __DS18B20_H
#define __DS18B20_H

#include "bsp.h"

/* 返回值：温度 ×10 的整数（如 365 表示 36.5℃），-1000 表示读取失败 */
#define DS18B20_ERR     (-1000)

void    ds18b20_init(void);
uint8_t ds18b20_start(void);            /* 启动一次温度转换（约 750ms） */
int16_t ds18b20_read(void);             /* 读温度，×10 */

/* 一步到位：启动 + 等待 + 读取（会阻塞约 800ms） */
int16_t ds18b20_get(void);

#endif /* __DS18B20_H */
